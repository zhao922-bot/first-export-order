import { z } from 'zod';
import {
  idSchema,
  textSchema,
  nonnegativeIntSchema,
  moneyMinorSchema,
  positiveIntSchema,
  unsignedDecimalSchema,
  probabilitySchema,
} from './common';
export const oaScenarioSchema = z.strictObject({
  id: idSchema,
  weight: positiveIntSchema.max(10000),
  firstDays: nonnegativeIntSchema.max(365),
  firstRatio: probabilitySchema,
  recoveryDays: nonnegativeIntSchema.max(365),
  recoveryRatio: probabilitySchema,
  firstEvidence: textSchema,
  recoveryEvidence: textSchema,
  lossEvidence: z.string().max(2000),
});
export const taxEvidenceIds = ['purchase', 'export', 'receipt', 'consistency'] as const;
export const collectionContentSchema = z.strictObject({
  puzzleId: idSchema,
  lcPuzzleId: idSchema,
  buyerShipmentDays: positiveIntSchema.max(60),
  ttDays: positiveIntSchema.max(60),
  lcDays: positiveIntSchema.max(60),
  presentationDays: positiveIntSchema.max(60),
  amendmentDays: positiveIntSchema.max(60),
  amendmentFeeFen: moneyMinorSchema.nonnegative(),
  lcBankFeeFen: moneyMinorSchema.nonnegative(),
  oaBankFeeFen: moneyMinorSchema.nonnegative(),
  oaScenarios: z.array(oaScenarioSchema).min(2).max(20),
  collectionFxFactor: unsignedDecimalSchema,
  rebateDays: positiveIntSchema.max(365),
  excellentReputation: z.number().int().min(0).max(100),
  taxEvidence: z.array(z.strictObject({ id: z.enum(taxEvidenceIds), label: textSchema })).length(4),
  messages: z.strictObject({
    TT: textSchema,
    LC_SIGHT: textSchema,
    OA_60: textSchema,
    exw: textSchema,
    tax: textSchema,
  }),
});
export const collectionStateSchema = z.strictObject({
  enteredDay: nonnegativeIntSchema,
  marks: z.array(idSchema),
  corrections: z.record(idSchema, z.string().max(200)),
  attempts: nonnegativeIntSchema,
  omissions: z.array(idSchema),
  falsePositives: z.array(idSchema),
  wrongCorrections: z.array(idSchema),
  documentsValid: z.boolean(),
  buyerShipmentVerified: z.boolean(),
  bankStatus: z.enum([
    'unchecked',
    'pending',
    'discrepancy',
    'ready',
    'partial',
    'settled',
    'loss',
  ]),
  presented: z.boolean(),
  collectionClosed: z.boolean(),
  released: z.boolean(),
  riskyAttempts: nonnegativeIntSchema,
  oaScenarioId: idSchema.nullable(),
  oaRoll: z.number().min(0).lt(1).nullable(),
  oaFirstChecked: z.boolean(),
  oaRecoveryAttempted: z.boolean(),
  outstandingUsdCent: moneyMinorSchema.nonnegative(),
  receivedUsdCent: moneyMinorSchema.nonnegative(),
  exchangeGainFen: moneyMinorSchema,
  bankFeeFen: moneyMinorSchema.nonnegative(),
  badDebtFen: moneyMinorSchema.nonnegative(),
  taxAnswers: z.record(z.enum(taxEvidenceIds), z.enum(['verified', 'missing']).optional()),
  taxErrors: z.array(z.enum(taxEvidenceIds)),
  taxReviewed: z.boolean(),
  taxEligible: z.boolean(),
  rebateAccruedFen: moneyMinorSchema.nonnegative(),
  rebateReceivedFen: moneyMinorSchema.nonnegative(),
  closed: z.boolean(),
});
export type CollectionState = z.infer<typeof collectionStateSchema>;
